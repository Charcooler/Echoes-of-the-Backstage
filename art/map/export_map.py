# Exports opera_house.blend to src/server/Services/MapService/MapLayout.luau and renders previews to preview/.
# Run after editing the .blend:
#   "D:\SteamLibrary\steamapps\common\Blender\blender.exe" opera_house.blend -b --python export_map.py
# build_opera_map.py also calls run() after building.
import bpy, math, os
from mathutils import Matrix, Vector

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "src", "server", "Services", "MapService", "MapLayout.luau")
PREVIEW = os.path.join(HERE, "preview")
Y_OFFSET = 20  # lifts the lowest floor (Blender Z -19) above Roblox's default baseplate

# Blender (x, y, z) -> Roblox (x, z, -y): Blender is Z-up with Y north, Roblox is Y-up.
C = Matrix(((1, 0, 0), (0, 0, 1), (0, -1, 0)))


def num(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def to_roblox(obj):
    loc, rot, _ = obj.matrix_world.decompose()
    rotation = C @ rot.to_matrix() @ C.transposed()
    position = C @ loc + Vector((0, Y_OFFSET, 0))
    return position, rotation, rot


def part_line(obj):
    position, rotation, _ = to_roblox(obj)
    d = obj.dimensions
    shape = obj["rbx_shape"]
    if shape == "Cylinder":
        # Roblox cylinders run along local X; the Blender cylinder runs along local Z (Roblox local Y).
        rotation = rotation @ Matrix.Rotation(math.radians(90), 3, "Z")
        size = (d.z, d.x, d.y)
    elif shape == "Ball":
        size = (d.x, d.x, d.x)
    else:
        size = (d.x, d.z, d.y)
    r, g, b = obj.color[:3]
    values = [r, g, b, obj["rbx_transparency"]]
    fields = [f'"{obj.name}"', f'"{obj["rbx_class"]}"', f'"{shape}"', f'"{obj["rbx_material"]}"']
    fields += [num(v) for v in values]
    fields.append("true" if obj["rbx_collide"] else "false")
    fields += [num(v) for v in size]
    fields += [num(v) for v in position]
    fields += [num(rotation[i][j]) for i in range(3) for j in range(3)]
    fields.append(f'"{obj["rbx_tag"]}"')
    return "\t\t{ " + ", ".join(fields) + " },"


def light_line(obj):
    position, _, rot = to_roblox(obj)
    direction = C @ (rot @ Vector((0, 0, -1)))
    r, g, b = obj.data.color
    fields = [f'"{obj["rbx_kind"]}"'] + [num(v) for v in (*position, *direction, r, g, b, obj["rbx_range"], obj["rbx_brightness"], obj["rbx_angle"])]
    return "\t\t{ " + ", ".join(fields) + " },"


def export():
    parts, lights, camera = [], [], None
    for obj in bpy.data.objects:
        kind = obj.get("rbx")
        if kind in ("part", "marker"):
            parts.append(part_line(obj))
        elif kind == "light":
            lights.append(light_line(obj))
        elif kind == "camera":
            position, _, rot = to_roblox(obj)
            look = position + C @ (rot @ Vector((0, 0, -1)))
            camera = "{ " + ", ".join(num(v) for v in (*position, *look)) + " }"
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("--!strict\n")
        f.write("-- GENERATED by art/map/export_map.py from art/map/opera_house.blend. Edit the .blend, not this file.\n")
        f.write("-- parts: { name, class, shape, material, r, g, b, transparency, canCollide, sx, sy, sz, px, py, pz, R00..R22, tag }\n")
        f.write("-- lights: { kind, px, py, pz, dx, dy, dz, r, g, b, range, brightness, angle }\n")
        f.write("-- menuCamera: { px, py, pz, lookX, lookY, lookZ }\n")
        f.write("return {\n")
        f.write(f"\tmenuCamera = {camera or 'nil'},\n")
        f.write("\tparts = {\n" + "\n".join(parts) + "\n\t},\n")
        f.write("\tlights = {\n" + "\n".join(lights) + "\n\t},\n")
        f.write("}\n")
    print(f"EXPORT_DONE {len(parts)} parts, {len(lights)} lights -> {OUT}")


def world_min_z(obj):
    return min((obj.matrix_world @ Vector(corner)).z for corner in obj.bound_box)


def render(name, camera_obj, hide):
    for obj in bpy.data.objects:
        obj.hide_render = obj.get("rbx") == "marker" or (obj.type == "MESH" and hide(obj))
    bpy.context.scene.camera = camera_obj
    bpy.context.scene.render.filepath = os.path.join(PREVIEW, f"{name}.png")
    bpy.ops.render.render(write_still=True)


def previews():
    os.makedirs(PREVIEW, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_WORKBENCH"
    scene.display.shading.color_type = "OBJECT"
    scene.display.shading.show_shadows = True
    scene.render.resolution_x, scene.render.resolution_y = 1100, 900
    menu_camera = scene.camera

    plan = bpy.data.objects.new("PlanCamera", bpy.data.cameras.new("PlanCamera"))
    plan.data.type = "ORTHO"
    plan.data.ortho_scale = 130
    plan.data.clip_end = 500
    plan.location = (-5, -9, 120)
    scene.collection.objects.link(plan)
    render("plan_stage_level", plan, lambda o: world_min_z(o) >= 15)
    render("plan_basement", plan, lambda o: world_min_z(o) >= 2.5)

    persp = bpy.data.objects.new("PerspCamera", bpy.data.cameras.new("PerspCamera"))
    persp.data.lens = 20
    scene.collection.objects.link(persp)
    scene.render.resolution_x, scene.render.resolution_y = 1100, 650
    for name, origin, target in (
        ("view_auditorium", (0, -60, 14), (0, 0, 8)),
        ("view_backstage", (-46, 24, 10), (40, 24, 7)),
        ("view_wings", (44, -12, 20), (0, 10, 4)),
        ("view_basement", (40, -12, -8), (-20, 10, -12)),
    ):
        persp.location = origin
        persp.rotation_euler = (Vector(target) - Vector(origin)).to_track_quat("-Z", "Y").to_euler()
        render(name, persp, lambda o: "Ceiling" in o.name or "Roof" in o.name)

    bpy.data.objects.remove(plan, do_unlink=True)
    bpy.data.objects.remove(persp, do_unlink=True)
    scene.camera = menu_camera


def run():
    export()
    previews()


if __name__ == "__main__":
    run()
